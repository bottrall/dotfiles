#!/usr/bin/env ruby
# frozen_string_literal: true

# Clock dropdown for waybar: a hotglass calendar overlay.
#
# Click the clock to open it under the bar; click anywhere else (the clock
# included) or press Esc to close it. The header names the selected day; the
# grid marks today with the accent.
#
# Closing on a click outside uses a click catcher: while the dropdown is
# open, a transparent full-screen layer sits just beneath it, and any click
# on it closes both. It can't close on focus loss instead: with Hyprland's
# follow_mouse, keyboard focus moves to any window the pointer merely
# crosses, which would shut it on the way from the clock to the grid. As
# with most menus, the dismissing click isn't passed through.
#
# Both are layer-shell surfaces, so they anchor to the screen edges and
# never pick up window borders or tiling. gtk4-layer-shell must be loaded
# before libwayland, so the script re-execs itself with it preloaded.
#
# Loading the GTK gems takes about a second, so the process stays resident
# after its first open (Hyprland pre-starts it with --gapplication-service)
# and the clock toggles it over D-Bus with `gapplication activate`, falling
# back to running this script.
#
# Needs the ruby-gnome gtk4 gem (`gem install gtk4`). Styling comes from
# calendar.css next to this file, generated by hotglass/generate from
# templates/calendar.css.erb.

require "date"
require "rbconfig"

LAYER_SHELL_LIB = "/usr/lib/libgtk4-layer-shell.so"
if File.exist?(LAYER_SHELL_LIB) && !ENV.fetch("LD_PRELOAD", "").include?(LAYER_SHELL_LIB)
  preload = [LAYER_SHELL_LIB, ENV.fetch("LD_PRELOAD", nil)].compact.reject(&:empty?).join(":")
  exec({ "LD_PRELOAD" => preload }, RbConfig.ruby, __FILE__, *ARGV)
end

require "gtk4"

module LayerShell; end
GObjectIntrospection::Loader.new(LayerShell).load("Gtk4LayerShell")

APP_ID = "dev.jake.hotglass.calendar"
CSS_PATH = File.join(__dir__, "calendar.css")
GRID = 12 # hotglass grid: gap below the bar and from the screen edge

# ---- pure helpers ------------------------------------------------------

module CalendarText
  module_function

  def days_in_year(year) = Date.new(year, 12, 31).yday

  # Overline, title and caption for the selected day.
  def header_lines(day, today)
    overline = day == today ? "Today" : day.strftime("%A")
    title = day == today ? day.strftime("%A %-d %B %Y") : day.strftime("%-d %B %Y")
    caption = "Week #{day.cweek} · Day #{day.yday} of #{days_in_year(day.year)}"
    [overline, title, caption]
  end

  def to_date(date_time) = Date.new(date_time.year, date_time.month, date_time.day_of_month)
end

# ---- UI ----------------------------------------------------------------

def make_layer(window, namespace:, anchors:, keyboard:, margin: 0, exclusive: nil)
  return unless LayerShell.supported?

  LayerShell.init_for_window(window)
  LayerShell.set_namespace(window, namespace)
  LayerShell.set_layer(window, LayerShell::Layer::OVERLAY)
  anchors.each do |edge|
    LayerShell.set_anchor(window, edge, true)
    LayerShell.set_margin(window, edge, margin)
  end
  LayerShell.set_keyboard_mode(window, keyboard)
  LayerShell.set_exclusive_zone(window, exclusive) if exclusive
end

def css_label(css_class)
  Gtk::Label.new("").tap do |label|
    label.xalign = 0.0
    label.add_css_class(css_class)
  end
end

# Transparent, full-screen (bar included: exclusive zone -1 ignores it),
# beneath the dropdown. Any click on it closes everything.
def build_catcher(app)
  Gtk::ApplicationWindow.new(app).tap do |catcher|
    catcher.decorated = false
    catcher.add_css_class("hotglass-calendar-catcher")
    edges = LayerShell::Edge
    make_layer(catcher, namespace: "hotglass-calendar-catcher",
                        anchors: [edges::TOP, edges::BOTTOM, edges::LEFT, edges::RIGHT],
                        keyboard: LayerShell::KeyboardMode::NONE, exclusive: -1)
    # GTK won't map a window with no content; an empty box fills it.
    catcher.child = Gtk::Box.new(:vertical, 0).tap do |fill|
      fill.hexpand = true
      fill.vexpand = true
    end
    click = Gtk::GestureClick.new
    click.button = 0 # any button
    click.signal_connect("pressed") { close_all(app) }
    catcher.add_controller(click)
  end
end

# Top-right under the bar (respects waybar's exclusive zone, so the margin is
# measured from the bar's bottom edge). Keyboard focus on demand: it has
# focus when it opens, so Esc works at once.
def build_dropdown(app, today)
  Gtk::ApplicationWindow.new(app).tap do |window|
    window.title = "Calendar"
    window.decorated = false
    window.resizable = false
    window.add_css_class("hotglass-calendar")
    window.set_default_size(360, -1)
    make_layer(window, namespace: "hotglass-calendar",
                       anchors: [LayerShell::Edge::TOP, LayerShell::Edge::RIGHT],
                       keyboard: LayerShell::KeyboardMode::ON_DEMAND, margin: GRID)

    labels = %w[overline title caption].map { css_label(it) }
    header = Gtk::Box.new(:vertical, 0)
    header.add_css_class("header")
    labels.each { header.append(it) }

    calendar = Gtk::Calendar.new
    refresh = lambda do
      CalendarText.header_lines(CalendarText.to_date(calendar.date), today)
                  .zip(labels).each { |text, label| label.text = text }
    end
    calendar.signal_connect("day-selected") { refresh.call }

    keys = Gtk::EventControllerKey.new
    keys.signal_connect("key-pressed") do |_controller, keyval, _keycode, _state|
      next false unless keyval == Gdk::Keyval::KEY_Escape

      close_all(app)
      true
    end
    window.add_controller(keys)

    body = Gtk::Box.new(:vertical, 0)
    body.append(header)
    body.append(calendar)
    window.child = body
    refresh.call
  end
end

def load_css
  return unless File.exist?(CSS_PATH)

  provider = Gtk::CssProvider.new
  provider.load(path: CSS_PATH)
  Gtk::StyleContext.add_provider_for_display(Gdk::Display.default, provider, Gtk::StyleProvider::PRIORITY_USER + 1)
end

# Closing destroys the windows but keeps the process (and the loaded gems)
# alive for the next open.
def close_all(app) = app.windows.each(&:destroy)

app = Gtk::Application.new(APP_ID, :default_flags)

app.signal_connect("startup") do |application|
  application.hold
  load_css
end

# Single instance: every activation (the clock via gapplication, a second
# launch) toggles. Windows are built fresh on each open so "today" is current.
app.signal_connect("activate") do |application|
  next close_all(application) unless application.windows.empty?

  build_catcher(application).present
  build_dropdown(application, Date.today).present
end

exit(app.run([$PROGRAM_NAME, *ARGV]))
