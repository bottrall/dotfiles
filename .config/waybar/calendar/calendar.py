#!/usr/bin/env python3
"""Clock dropdown for waybar: a hotglass calendar overlay.

Click the clock to open it under the bar (placed by a Hyprland window rule
on its app id); click the clock again, press Esc, or click anywhere else to
close it. The header names the selected day, the grid marks today with the
accent, and Enter or the footer button opens the selected day in Google
Calendar in the default browser.

Styling comes from calendar.css next to this file, generated by
hotglass/generate from templates/calendar.css.erb.
"""

import sys
from datetime import date
from pathlib import Path

import gi

gi.require_version("Gtk", "4.0")
gi.require_version("Gdk", "4.0")
from gi.repository import Gdk, Gio, GLib, Gtk  # noqa: E402

APP_ID = "dev.jake.hotglass.calendar"
CSS_PATH = Path(__file__).with_name("calendar.css")
GOOGLE_DAY_URL = "https://calendar.google.com/calendar/r/day/{y}/{m}/{d}"


# ---- pure helpers -------------------------------------------------------


def days_in_year(year: int) -> int:
    return (date(year + 1, 1, 1) - date(year, 1, 1)).days


def header_lines(day: date, today: date) -> tuple[str, str, str]:
    """Overline, title and caption for the selected day."""
    overline = "Today" if day == today else day.strftime("%A")
    title = f"{day.strftime('%A') + ' ' if day == today else ''}{day.day} {day.strftime('%B %Y')}"
    caption = f"Week {day.isocalendar().week} · Day {day.timetuple().tm_yday} of {days_in_year(day.year)}"
    return overline, title, caption


def google_url(day: date) -> str:
    return GOOGLE_DAY_URL.format(y=day.year, m=day.month, d=day.day)


def to_date(dt: GLib.DateTime) -> date:
    return date(dt.get_year(), dt.get_month(), dt.get_day_of_month())


# ---- UI -----------------------------------------------------------------


def label(text: str, css_class: str) -> Gtk.Label:
    widget = Gtk.Label(label=text, xalign=0)
    widget.add_css_class(css_class)
    return widget


def build_window(app: Gtk.Application, today: date) -> Gtk.ApplicationWindow:
    window = Gtk.ApplicationWindow(application=app, title="Calendar", decorated=False, resizable=False)
    window.add_css_class("hotglass-calendar")
    window.set_default_size(360, -1)

    overline, title, caption = (label("", c) for c in ("overline", "title", "caption"))
    header = Gtk.Box(orientation=Gtk.Orientation.VERTICAL)
    header.add_css_class("header")
    for widget in (overline, title, caption):
        header.append(widget)

    calendar = Gtk.Calendar()
    open_button = Gtk.Button(label="Open in Google Calendar")
    open_button.add_css_class("open")

    def selected() -> date:
        return to_date(calendar.get_date())

    def refresh(*_args) -> None:
        texts = header_lines(selected(), today)
        for widget, text in zip((overline, title, caption), texts):
            widget.set_label(text)

    def open_selected(*_args) -> None:
        Gio.AppInfo.launch_default_for_uri(google_url(selected()), None)
        window.close()

    def on_key(_controller, keyval, _keycode, _state) -> bool:
        if keyval == Gdk.KEY_Escape:
            window.close()
            return True
        if keyval in (Gdk.KEY_Return, Gdk.KEY_KP_Enter):
            open_selected()
            return True
        return False

    # Close when focus moves elsewhere, like a menu. Only after the window
    # has been active once, so it can't close before it's been seen.
    seen_active = {"value": False}

    def on_active(*_args) -> None:
        if window.is_active():
            seen_active["value"] = True
        elif seen_active["value"]:
            window.close()

    calendar.connect("day-selected", refresh)
    open_button.connect("clicked", open_selected)
    keys = Gtk.EventControllerKey()
    keys.connect("key-pressed", on_key)
    window.add_controller(keys)
    window.connect("notify::is-active", on_active)

    body = Gtk.Box(orientation=Gtk.Orientation.VERTICAL)
    for widget in (header, calendar, open_button):
        body.append(widget)
    window.set_child(body)
    refresh()
    return window


def load_css() -> None:
    if not CSS_PATH.exists():
        return
    provider = Gtk.CssProvider()
    provider.load_from_path(str(CSS_PATH))
    Gtk.StyleContext.add_provider_for_display(
        Gdk.Display.get_default(), provider, Gtk.STYLE_PROVIDER_PRIORITY_USER + 1
    )


def main() -> int:
    app = Gtk.Application(application_id=APP_ID)

    # Single instance: a second launch (clicking the clock again) re-activates
    # the running one, which then closes, so the clock toggles the dropdown.
    def on_activate(application: Gtk.Application) -> None:
        if application.get_active_window():
            application.get_active_window().close()
            return
        load_css()
        build_window(application, date.today()).present()

    app.connect("activate", on_activate)
    return app.run(sys.argv[:1])


if __name__ == "__main__":
    sys.exit(main())
